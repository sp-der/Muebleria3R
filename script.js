const observer = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.09, rootMargin: "0px 0px -32px" });

function observeReveals() {
  document.querySelectorAll(".reveal:not(.visible)").forEach((el) => observer.observe(el));
}

function validateForm() {
  let valid = true;
  form.querySelectorAll("[required]").forEach((field) => {
    const empty = !String(field.value || "").trim();
    field.setAttribute("aria-invalid", String(empty));
    if (empty) valid = false;
  });

  const phone = form.elements.phone;
  const digits = String(phone.value || "").replace(/\D/g, "");
  if (digits.length < 7) {
    phone.setAttribute("aria-invalid", "true");
    valid = false;
  }
  return valid;
}

form.addEventListener("input", (event) => {
  if (event.target.matches("input, select, textarea")) {
    event.target.removeAttribute("aria-invalid");
  }
});

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  formStatus.textContent = "";
  formStatus.className = "form-status";

  if (!validateForm()) {
    formStatus.textContent = translations[currentLang].formValidation;
    formStatus.classList.add("error");
    return;
  }

  const submitButton = form.querySelector(".form-submit");
  submitButton.disabled = true;
  submitButton.classList.add("loading");

  const payload = Object.fromEntries(new FormData(form).entries());
  payload.language = currentLang;

  try {
    const response = await fetch("/api/contact", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload)
    });

    const data = await response.json().catch(() => ({}));
    if (!response.ok || !data.ok) throw new Error(data.error || "Request failed");

    form.reset();
    document.querySelector("#started-at").value = String(Date.now());
    formStatus.textContent = translations[currentLang].formSuccess;
    formStatus.classList.add("success");
  } catch (error) {
    formStatus.textContent = translations[currentLang].formError;
    formStatus.classList.add("error");
  } finally {
    submitButton.disabled = false;
    submitButton.classList.remove("loading");
  }
});

document.querySelector("#started-at").value = String(Date.now());
document.querySelector("#year").textContent = new Date().getFullYear();

setLanguage(currentLang);
observeReveals();